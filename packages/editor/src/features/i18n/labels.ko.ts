/**
 * history 라벨 중 뒤에 이름이 붙는 꼴(`Import {파일}`, `Apply {프리셋}` ...). 접두 -> 한글 틀. `{}` 자리에 이름이 들어간다.
 * 이름(파일, 프리셋, 효과 이름)은 번역하지 않는다.
 */
export const HISTORY_PATTERNS_KO: ReadonlyArray<readonly [prefix: string, template: string]> = [
  ['Import Captions ', '자막 가져오기: {}'],
  ['Import ', '가져오기: {}'],
  ['Apply ', '{} 적용'],
  ['Add Track Effect ', '트랙 효과 추가: {}'],
  ['Time Interpolation: ', '시간 보간: {}'],
  ['Synchronize ', '싱크 맞추기 {}'],
  ['Label ', '라벨: {}'],
  ['New ', '새로 만들기: {}'],
  ['Edit ', '편집: {}'],
];

/** 커맨드 id 의 한글 라벨. 사전에 없으면 `fallback`(보통 엔진 라벨), 그것도 없으면 id */
export function commandLabelKo(id: string, fallback?: string | null): string {
  return COMMAND_LABELS_KO[id] ?? fallback ?? id;
}

/**
 * 실행 취소·다시 실행의 history 라벨을 한글로. 순서: history 사전 -> 카탈로그에서 같은 라벨의 커맨드를 찾아 커맨드 사전 ->
 * 접두 패턴 -> 원문. 한글이 이미 들어 있는 라벨(화면 쪽 sh 커맨드의 "화면 비율 세로 9:16" 등)은 그대로 둔다.
 */
export function historyLabelKo(label: string, commands: ReadonlyArray<Pick<CommandSpec, 'id' | 'label'>> = []): string {
  if (!label || /[가-힣]/.test(label)) return label;
  const direct = HISTORY_LABELS_KO[label];
  if (direct) return direct;
  const bare = label.replace(/[.…]+$/, '');
  for (const c of commands) {
    if (c.label.replace(/[.…]+$/, '') === bare) {
      const ko = COMMAND_LABELS_KO[c.id];
      if (ko) return ko.replace(/\.{3}$/, '');
    }
  }
  for (const [prefix, template] of HISTORY_PATTERNS_KO) {
    if (label.startsWith(prefix) && label.length > prefix.length) {
      const name = label.slice(prefix.length);
      return template.replace('{}', EFFECT_NAMES_KO[name] ?? name);
    }
  }
  return label;
}

/** 번역 사전이 다루는 커맨드인지(메뉴 경로가 있는 엔진 커맨드 전부가 대상이다) */
export function needsTranslation(c: Pick<CommandSpec, 'menu'>): boolean {
  return c.menu.length > 0;
}

/** 메뉴에 노출되는데 사전에 없는 커맨드 id. 비어 있어야 한다(단위·엔진 테스트가 강제) */
export function untranslatedMenuCommands(commands: ReadonlyArray<Pick<CommandSpec, 'id' | 'menu'>>): string[] {
  return commands.filter((c) => needsTranslation(c) && !(c.id in COMMAND_LABELS_KO)).map((c) => c.id);
}
